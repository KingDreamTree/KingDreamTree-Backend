import random


#: 부위마다 **어디를 볼지**. 위치만 주면 부위가 달라도 같은 문장이 나온다
#  (실측 2026-08-20 — 상완·전완 4개가 "더 가늘어 보입니다" 한 문장으로 통일됐다).
#  ⚠️ 완성 문장이 아니라 **관찰 지점**이다. 서술은 매번 새로 쓰게 한다.
#  ⚠️ 굵기가 아니라 **선과 면**으로 적는다 — «굵기» 를 보라고 하면 «가늘다/굵다» 판정이
#     돌아온다. 몸통의 옆선 곡선은 사진 경로 프롬프트에만 있던 관찰이라 여기로 옮겼다.
_LOOK_AT: dict[str, str] = {
    "Torso": "어깨에서 허리로 폭이 좁아지는 정도, 허리 옆선이 안으로 들어가는지 바깥으로 볼록한지, "
    "가슴·복부의 앞뒤 두께감",
    "Upper_Arm": "어깨에서 팔꿈치로 내려오는 선, 팔 윗면이 부푸는 위치와 정도, 어깨와 만나는 지점의 두께",
    "Lower_Arm": "팔꿈치에서 손목으로 좁아지는 기울기, 전완 가운데가 도톰하게 올라오는 정도",
    "Upper_Leg": "골반에서 무릎으로 좁아지는 선, 허벅지 바깥선과 안쪽선의 굴곡",
    "Lower_Leg": "종아리가 가장 부푸는 위치와 정도, 발목으로 좁아지는 기울기",
}


def look_at(class_name: str) -> str | None:
    """이 부위에서 볼 지점. 좌우 접두사를 떼고 찾는다 (좌우는 볼 지점이 같다)."""
    for prefix in ("Left_", "Right_"):
        if class_name.startswith(prefix):
            return _LOOK_AT.get(class_name[len(prefix) :])
    return _LOOK_AT.get(class_name)


#: 카드마다 **코드가 서로 다르게 배정하는** 문장 방식 — 첫 문장의 시작 틀 (2026-09-12).
#  ⚠️ 왜 모델에게 «다양하게 써라» 가 아니라 코드가 배정하는가. 부위 9개를 한 응답에서 쓰면
#     모델은 첫 카드의 문형을 나머지가 따라간다 — 규칙을 몇 줄 적어도, 온도를 올려도 안 풀렸다
#     (실측 2026-09-12, 온도 0.7: 한 회차 6장이 «목표 체형보다 두꺼운 경향이 있습니다», 게다가
#     같은 사진 상완의 판정 방향이 회차마다 뒤집혔다). 그래서 다양성은 코드가 책임진다 —
#     카드마다 다른 시작 틀을 무작위로 배정하고, 모델은 내용만 채운다.
#  ⚠️ 끝맺음은 배정하지 않는다 (2026-09-12 재측정). 시작 틀과 끝맺음을 둘 다 강제하니 모델이
#     둘을 억지로 이어 붙여 «…높은 차이가 납니다» 같은 비문이 나왔다. 시작 틀만으로도 흔한 틀이
#     차지한 카드가 30/45 → 3/45 로 줄었다 — 끝맺음까지 묶을 이유가 없다.
#  ⚠️ 틀이 해로운 건 **모든 카드가 같은 틀을 받을 때**다 (2026-08-19: 골격 하나를 주자 다섯
#     부위가 같게 나왔다). 카드마다 다른 틀을 받으면 베껴 써도 서로 다르다.
#  ⚠️ «…» 자리만 있는 틀이다 — 내용이 든 예문은 넣지 않는다. 내용은 다른 부위로 옮겨 붙는다
#     (실측: 예시의 «바지에 가려» 가 몸통 카드에 그대로 붙었다).
_OPENINGS: tuple[str, ...] = (
    "목표 사진은 …인데, 지금은 …",
    "지금 사진에서는 …이 먼저 눈에 들어오고 …",
    "목표 체형과 달리 …",
    "…에서 …로 이어지는 선을 보면 …",
    "두 사진을 나란히 놓으면 …",
    "가장 크게 다른 곳은 …",
    "…은 목표와 비슷하지만, …",
    "…을 기준으로 견주면 …",
    "위에서 아래로 따라가 보면 …",
    "폭만 놓고 보면 …",
    "바깥 윤곽선으로 보면 …",
    "입체감으로 보면 …",
    "눈에 띄는 건 …",
    "지금은 …, 목표는 …",
    "전체 윤곽은 …, 그중에서도 …",
    "…부분을 짚어 보면 …",
    "목표 사진의 같은 자리와 견주면 …",
    "옆선의 방향으로 보면 …",
    "…과 이어지는 지점에서 …",
    "먼저 …, 이어서 …",
)


def assign_frames(names: list[str], rng: random.Random | None = None) -> dict[str, str]:
    """부위마다 서로 다른 시작 틀을 무작위로 배정한다 — 부위 메시지의 «문장 방식».

    요청마다 달라지므로 같은 사진을 다시 봐도 말투가 달라진다. 판정은 온도가 낮아 흔들리지 않는다.
    부위가 틀 수보다 많으면 돌려 쓴다 (지금은 9부위 < 20개).
    """
    rng = rng or random.Random()
    openings = rng.sample(_OPENINGS, k=min(len(names), len(_OPENINGS)))
    return {n: f"첫 문장을 «{openings[i % len(openings)]}» 로 시작" for i, n in enumerate(names)}
