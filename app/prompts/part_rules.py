#: 부위마다 **어디를 볼지**. 위치만 주면 부위가 달라도 같은 문장이 나온다
#  (실측 2026-08-20 — 상완·전완 4개가 "더 가늘어 보입니다" 한 문장으로 통일됐다).
#  ⚠️ 완성 문장이 아니라 **관찰 지점**이다. 서술은 매번 새로 쓰게 한다.
#  ⚠️ 굵기가 아니라 **선과 면**으로 적는다 — «굵기» 를 보라고 하면 «가늘다/굵다» 판정이
#     돌아온다. 몸통의 옆선 곡선은 사진 경로 프롬프트에만 있던 관찰이라 여기로 옮겼다.
_LOOK_AT: dict[str, str] = {
    "Torso": "어깨에서 허리로 폭이 좁아지는 정도, 허리 옆선이 안으로 들어가는지 바깥으로 볼록한지, "
    "가슴·복부의 앞뒤 두께감",
    "Upper_Arm": "어깨에서 팔꿈치로 내려오는 선, 팔 윗면이 부푸는 위치와 정도, 어깨와 만나는 지점의 두께",
    "Lower_Arm": "팔꿈치에서 손목으로 좁아지는 기울기, 전완 가운데가 도톰하게 올라오는 정도",
    "Upper_Leg": "골반에서 무릎으로 좁아지는 선, 허벅지 바깥선과 안쪽선의 굴곡",
    "Lower_Leg": "종아리가 가장 부푸는 위치와 정도, 발목으로 좁아지는 기울기",
}


def look_at(class_name: str) -> str | None:
    """이 부위에서 볼 지점. 좌우 접두사를 떼고 찾는다 (좌우는 볼 지점이 같다)."""
    for prefix in ("Left_", "Right_"):
        if class_name.startswith(prefix):
            return _LOOK_AT.get(class_name[len(prefix) :])
    return _LOOK_AT.get(class_name)


#: 카드마다 **코드가 서로 다르게 배정하는** 문장 방식 — 첫 문장의 시작 틀 (2026-09-12).
#  ⚠️ 왜 모델에게 «다양하게 써라» 가 아니라 코드가 배정하는가. 부위 9개를 한 응답에서 쓰면
