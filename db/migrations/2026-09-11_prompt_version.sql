CREATE TABLE IF NOT EXISTS prompt_version (
    prompt_version_id  UUID          PRIMARY KEY DEFAULT gen_random_uuid(),
    name               VARCHAR(60)   NOT NULL,
    version            INTEGER       NOT NULL CHECK (version >= 1),
    content            TEXT          NOT NULL,
    note               TEXT,
    is_active          BOOLEAN       NOT NULL DEFAULT false,
    created_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT prompt_version_uniq UNIQUE (name, version)
);

-- 이름마다 활성 버전은 하나 — 둘이 켜지면 어느 쪽이 쓰일지 정해지지 않는다.
CREATE UNIQUE INDEX IF NOT EXISTS prompt_version_one_active_idx
    ON prompt_version (name) WHERE is_active;

