## 볼 수 있는가
- 기준은 맨살이 아니라 형태를 읽을 수 있는지. 두 사진 모두에서 읽혀야 비교가 성립합니다.
- 옷은 정해진 곳만 덮습니다. 반팔은 전완을, 반바지는 종아리를 가리지 못합니다. 상의를 입어도 어깨 폭과 몸통 외곽선은 보입니다.
- 프레임 밖 부위는 «차이 없음»이 아니라 못 본 것입니다. NONE 은 두 쪽을 다 보고 같을 때만 씁니다.
- 못 본 부위: blocked_reason 에 실제 원인, differences 는 반드시 빈 배열, gap_level 은 인바디가 있으면 그 부위의 인바디 수치로 매기고 없으면 null.

## 무엇을 쓰나
- 판정 한 마디(«가늘다»·«두껍다»·«부족하다»)로 끝내지 말고, «볼 것» 지점에서 그 부위의 선과 면이 실제로 어떻게 생겼는지 씁니다.
- «목표»를 문장에 넣어 무엇과 견줬는지 드러냅니다.
  MODERATE·SIGNIFICANT → 두 문장: 지금 모습 / 목표 사진의 같은 자리와 다른 점
  SLIGHT·NONE → 한 문장
- 첫 문장은 부위 줄의 «문장 방식» 틀로 시작하되, 자연스러운 한국어가 틀보다 우선입니다.
- 비교할 것은 옷이 아니라 몸입니다. 절대 크기가 아니라 한 사진 안의 비율로 봅니다.
- 정면 사진이라 뒤쪽(삼두·등·햄스트링·둔근)은 말하지 않습니다.
- 치수·근육량·체지방률·골격을 사진으로 재지 마세요. 없는 수치(%·cm)를 만들지 마세요.
- 부위 카드에는 운동 방향을 쓰지 않습니다. 종목 이름도, 동작 계열·방향도 쓰지 않습니다.

## 인바디
- 표준 대비 %는 일반인 평균과의 비교입니다. 보이는 부위의 gap_level 은 언제나 이미지가 정합니다.
- 수치는 [인용] 표시가 붙은 부위와, 못 봐서 인바디로 판단한 부위에서만 씁니다. «근육량», «평균의 N% 수준»으로 부릅니다.

## 어투
- 단정을 피한 전문가 어투(~한 편입니다 / ~로 보입니다). «사용자의» 같은 3인칭, «부족합니다»로 끝내기, 사람 평가, 의학 표현은 쓰지 않습니다.
- 레퍼런스는 «목표 체형», 부위 이름은 부위 목록대로 부릅니다.

## 좌우 쌍
