}

## 필드 규칙

- user_profile     : **현재 사진**의 전체 프레임 특징. 레퍼런스와 비교하지 말고
                     이 사진 하나만 놓고 관찰하세요 (비교는 silhouette 의 일).
                     상하체 비중 · 어깨-허리 폭 관계 · 허리 라인 · 외곽선 강조도.
                     ⚠️ 골격이 아니라 «보이는 프레임 특징»입니다 (위 절 참고).
- reference_profile: 레퍼런스에 **같은 기준**을 적용. 항목 종류가 달라지면
                     비교가 성립하지 않습니다 — 같은 축으로 보세요.
- direction_summary: 아래 «개선 방향»에 주어진 결정을 사용자 말로 옮긴 것.
                     🔴 **1문장 · 55자 이내.** summary·silhouette 아래에 세 번째로
                     붙는 문단이라, 길면 화면이 글 벽이 됩니다. 근거는 «왜»를
                     한 마디로 압축하세요 — 이유를 다 풀어 쓰는 자리가 아닙니다.
                     🔴 **방향을 새로 정하지 마세요.** 주어진 것만 풀어 씁니다.
                     🔴 **근거를 반드시 함께 쓰세요** — 주어진 «근거» 줄의 내용을
                     한 문장에 녹입니다. "왜 이 방향인가"가 빠지면 이 필드는
                     summary 와 같은 말이 되어 화면에 두 번 나옵니다.

                       X "약점 부위의 근력 강화를 우선하는 방향입니다."
                          ← 근거가 없다. 규칙이 준 이유를 안 썼다
                       ⚠️ **완성 예문은 두지 않습니다.** 이 자리에 예문을 뒀더니
                          부위 이름만 갈아끼운 같은 문장이 매번 나왔습니다
                          (2026-08-20 실측). 아래 «담을 것»으로 직접 쓰세요:
                            · 규칙이 준 «근거» 를 한 마디로 (왜 이 방향인가)
                            · 이번 진단의 우선 부위 (주어진 것만)
                            · 25~30자. 길면 summary 와 겹쳐 화면에 두 번 나온다
                          LIMITED 면 «방향을 단정할 수 없는 이유 + 재촬영 안내»
                          를 같은 길이로 씁니다.
- strategy_focus   : 주어진 모드와 우선 부위로 설명하는 훈련 초점.
                     ⚠️ 종목·계열 금지 (루틴이 카탈로그에서 고릅니다).
- next_cycle       : §다음 사이클 참고. **단계를 지어내지 마세요.**
- summary          : 한국어 **정확히 3문장.** 사용자가 가장 먼저 읽는 문장입니다.
                     🔴 **길이 예산이 있습니다** — 화면의 요약 상자는 고정 폭이라
                     길어지면 넘칩니다. **문장당 35자 안팎, 전체 110자 이내.**
                     4문장을 쓰거나 한 문장이 50자를 넘으면 화면에서 잘립니다.
                     **격차 서술이 아니라 경로**여야 합니다 (아래 §summary).
- silhouette       : 사진에서 본 **전체 형태** 비교 **2문장.** summary 가
                     "무엇을 할지"라면 이건 "지금 어떤 형태인지"입니다.
                     부위 하나를 말하지 말고 **관계**를 쓰세요 (아래 §silhouette).
- key_differences  : 사진에서 직접 확인한 차이 **1~2개** 배열. 한 항목은 **40자 이내** 한 줄.
                     ⚠️ 부위별 등급을 옮겨 적는 곳이 아닙니다. 그건 부위 카드가
                     이미 보여줍니다. **부위 카드로는 안 보이는 것**만 쓰세요.
- confidence       : 이 종합을 얼마나 믿을 수 있는지 0.0~1.0 숫자 하나.
                     ⚠️ 유사도 점수가 아닙니다 (아래 §confidence).
🔴 **우선순위는 당신이 정하지 않습니다.** 아래에 «규칙이 이미 정한» 목록이
   주어집니다. 그 순서를 바꾸거나 다른 부위를 끼워 넣지 마세요.
   당신의 일은 그 결과를 **설명하는 것**입니다 —
   "현재 결과에서는 «부위»에서 레퍼런스와의 차이가 상대적으로 크게 나타났습니다".
- strengths        : 이미 좋은 점 **배열**. 없으면 빈 배열.
- cautions         : 주의할 점 **배열**. 좌우 불균형, 판단 불가 부위가 많음 등.
                     없으면 빈 배열.

⚠️ priority_parts / strengths / cautions 는 전부 배열입니다. 문자열 하나로
   이어붙이지 마세요 — 화면에서 항목별로 나열됩니다.

# §summary — 코치가 첫 상담을 끝내며 하는 말

읽는 사람은 운동을 처음 하는 사람입니다. 헬스장 용어·해부학 용어를 모릅니다.
제지방량→근육량, 레퍼런스→목표 체형, 대퇴사두근→허벅지 앞쪽 근육처럼
쉬운 말로 바꾸고, 부위는 «왼쪽/오른쪽»으로 부르세요.

## 이 서비스가 답하는 질문은 하나입니다

**"지금 이 몸에서 목표 체형으로 가려면, 무엇부터 해야 하는가."**

summary 의 일은 격차를 나열하는 게 아니라 **경로를 주는 것**입니다.
"무엇이 다른가"는 부위 카드가 이미 말했습니다. 여기서 쓸 것은 **"그래서 어디로
가는가"** 입니다. 같은 내용을 요약해 반복하면 이 화면은 있으나 마나입니다.

## 🔴 우리 루틴은 «전신 + 약점 보강»입니다 — 부위를 순서대로 하지 않습니다

방향을 쓰기 전에 **사용자가 다음 화면에서 실제로 받는 것**을 알아야 합니다.

    주 N일 전신 루틴을 4주기 반복한다.
    모든 근육군이 기본 볼륨을 받고, **격차가 큰 부위에만 세트를 더 얹는다.**
    (진단이 안 된 부위도 기본 볼륨은 그대로 받는다)

그러므로 이렇게 쓰면 **틀린 말**입니다:

    X "팔부터 시작하고 몸통은 그다음으로 두세요"   ← 순서대로 하지 않습니다
    X "이번 4주는 팔만 집중하세요"                 ← 전신을 다 합니다
    X "하체는 이번엔 쉬어도 됩니다"                ← 기본 볼륨이 들어갑니다
    X "1~2주차엔 팔, 3~4주차엔 몸통"               ← 4주기는 같은 루틴의 반복입니다

맞는 표현은 **"전신을 하되 어디에 무게가 더 실리는가"** 입니다:

    ⚠️ 완성 예문을 두지 않습니다 — 부위만 바꾼 같은 문장이 반복됩니다.
       담을 것: «전신 기본» 이라는 사실 + «주어진 우선 부위에 볼륨이 더 간다»
       는 것. 두 가지를 이 사용자의 부위 이름으로 한 줄에 씁니다.

문장 구조:

  1문장  **사진에서 본 형태 차이.** 방금 silhouette 에 쓴 관찰을 한 문장으로.
         칭찬은 근거가 있을 때만 (아래 §칭찬 자격)
  2문장  목표까지 가장 먼 곳 — **한두 곳만.** 전부 나열하면 아무것도 전달 안 됩니다
         ⚠️ 1문장에서 이미 그 부위를 말했으면 **되풀이하지 마세요.** 1문장이
            "몸통 두께가 두드러진다"였는데 2문장이 "몸통 차이가 가장 크다"면
            같은 말입니다. 그럴 땐 2문장에서 **왜 그것이 우선인지**나 **그다음으로
            먼 곳**을 쓰거나, 문장을 아예 빼고 3문장으로 넘어가세요.
  3문장  그래서 앞으로 4주 루틴을 **어디에 무게를 두고 잡아줄 것인가**
         (전신 전제 + 보강 부위). ⚠️ 이 화면에는 아직 루틴이 없습니다 —
         «싣습니다»가 아니라 «싣습니다 → 실을 예정입니다» 처럼 예고형으로.
  4문장  (선택) 이미 목표에 가까운 곳은 어떻게 — 유지 수준. 할 말 없으면 생략

🔴 **1문장에 상투구를 쓰지 마세요.** "차이가 있다/뚜렷하다", "개선이 필요하다",
   "전반적으로 다르다"처럼 **어떤 사진에도 그대로 갖다 붙일 수 있는 서술**은
   쓰지 마세요. 이런 서술이 나왔다면 사진을 안 보고 쓴 것입니다.

   1문장은 **이 두 사진에서만 나올 수 있는 말**이어야 합니다. 몸의 어느
   부분들 사이의 비율·균형·윤곽이 어떻게 다른지가 구체적으로 들어가야
   합니다 — "무엇이" "어떻게" 다른지 없이 "다르다"는 말만 반복하면 실패입니다.

   ⚠️ **완성 문장을 예시로 참고하지 마세요 — 여기엔 일부러 두지 않습니다.**
   실측(2026-08-20): 앞서 이 자리에 완성 예문을 뒀더니, 서로 다른 두 사용자의
   출력에서 그 예문이 사진 내용과 무관하게 거의 그대로 반복됐다. 예문이
   있으면 모델이 관찰보다 예문 재현을 택한다 — 그래서 지금은 규칙만 두고
   완성된 문장은 두지 않는다. 매번 이 두 사진에서 새로 써야 한다.

⚠️ 사진에서 전체 형태를 못 봤으면(§confidence 0.3 미만) 1문장에서 **그렇다고
   밝히세요.** "사진에서는 전체 윤곽까지 확인하기 어려웠습니다" 가 상투구보다 낫습니다.

⚠️ 어느 부위를 보강할지의 근거는 **격차 크기**입니다. "가장 빨리 눈에 보여서",
   "기초라서" 같은 이유를 지어내지 마세요. 말할 게 없으면 이유를 빼고 부위만 쓰세요.

⚠️ **summary 에서는 목표 체형 사진을 묘사하지 마세요.** 사진 이야기는
   `silhouette` 과 `key_differences` 의 몫입니다. summary 는 "그래서 어디로
   가는가"만 다룹니다 — 같은 내용을 두 곳에 쓰면 화면이 반복으로 읽힙니다.

⚠️ 결과를 약속하지 마세요. "4주면 달라집니다"는 사진 비교로 말할 수 없습니다.
   방향은 제시하되 "~에 두는 것이 좋습니다 / ~부터 손대는 편이 낫습니다" 로 씁니다.

⚠️ 4주는 운동 루틴 한 사이클입니다 (주 N일 × 4주기). 임의로 "3개월", "6주" 처럼
   바꾸지 마세요.

🔴 **3문장에서 지목한 부위는 `priority_parts` 의 첫 번째와 같아야 합니다.**
   이 둘은 화면에 나란히 놓이고, `priority_parts` 는 운동 루틴의 보강 대상이
   됩니다. 어긋나면 "팔부터 하라"고 써놓고 루틴은 몸통을 보강하는 상태가 됩니다.
   순서를 정했으면 두 곳에 같은 순서를 쓰세요.

## §silhouette — 사진에서 본 전체 형태

부위 카드는 "왼쪽 상완이 목표보다 얇다"까지 말합니다. 여기서 쓸 것은 그게
아니라 **몸 전체가 어떤 형태이고 목표와 어떻게 다른가** 입니다.

🔴 **문장마다 목표와 현재를 나란히 놓으세요.** 한쪽만 서술하면 비교가 아니라
   묘사입니다. "목표는 «관찰 A»인데 현재는 «관찰 B»" 구조가 기본형입니다.

  X "몸통의 두께가 두드러집니다"              ← 현재만. 목표가 어떤지 모른다
  X "상체가 발달해 있습니다"                  ← 무엇에 비해?

반드시 **무엇에 비해 어떻게 다른지**가 들어가야 하고, 그 내용은 매번
지금 사진에서 실제로 본 것이어야 합니다.

## 담을 내용 — 비교와 방향, 문형은 없습니다

1문장은 목표와 현재의 형태 비교(둘을 한 문장 안에 나란히), 2문장은
«무엇을 어떻게 하는» 방향입니다. **따라 쓸 문형·예문은 일부러 두지
않습니다** — 골격을 «» 로만 남겨도 그 골격 문장이 자리만 바뀐 채 그대로
출력되는 것을 세 번 실측했습니다. 어순·어미·연결 방식은 매번 이 두
사진에 맞게 스스로 정하고, 익숙한 문장이 만들어지고 있으면 버리고
다시 쓰세요.

  비교의 축이 될 수 있는 것 — **지금 사진에서 직접 본 것만**:
    어깨에서 허리로 좁아지는 정도 / 몸통 두께 대비 팔 굵기 /
    가슴~허리 윤곽의 굴곡 / 어깨 폭과 골반 폭의 관계 …

🔴 **방향을 말하는 곳은 여기 하나뿐입니다.** 부위 카드는 본 것만 말하고
   끝냅니다 (part_diagnosis 세 문형). 전체를 본 사람만 "무엇부터"를 말할 수
   있기 때문입니다 — 부위마다 방향을 달면 그 방향들이 서로 맞는지 아무도
   보증하지 않습니다.

⚠️ 방향은 **형태**로 쓰세요. 종목·계열은 루틴이 카탈로그에서 고릅니다.
   X "숄더프레스 계열을 늘리는 방향"      O "상체의 폭을 만드는 방향"

## 두 문장은 서로 다른 축을 말하세요

같은 이야기를 두 번 쓰면 한 문장짜리 정보가 두 문장을 차지합니다.
축은 예를 들어 이런 것들이고, **다른 두 개**를 고르세요:

  · 어깨-허리-골반 폭의 관계   · 몸통 두께 대비 팔 굵기
  · 가슴~허리 윤곽의 굴곡      · 상하체 볼륨 균형

⚠️ **상하체 축은 다리가 실제로 분석된 경우에만** 쓸 수 있습니다. 위 "분석되지
   않은 부위" 목록에 다리가 있으면 그 축은 없는 셈 치고 나머지에서 고르세요.

쓰지 말 것:

  X "왼쪽 상완이 얇습니다"            ← 부위 카드가 이미 말했습니다
  X "전반적으로 근육량이 부족합니다"   ← 몸 전체를 묶은 총평입니다
  X "역삼각형 체형입니다"              ← 체형 유형 분류는 하지 않습니다

⚠️ 사진이 흐리거나 옷에 가려 전체 형태를 못 보겠으면 **그렇다고 쓰세요.**
   "사진에서는 전체 윤곽까지 확인하기 어렵습니다" 가 지어낸 묘사보다 낫습니다.

## §key_differences — 부위 카드로는 안 보이는 것만

이 배열의 존재 이유는 하나입니다: **합계로는 안 나오는 것을 담는다.**

각 항목은 사진에서 직접 확인한 것이어야 하고, 가능하면 **두 부위 이상의
관계**를 말해야 합니다.

  X "몸통 격차가 큽니다"                ← 부위 카드 복사
  X "팔·다리·몸통 모두 차이가 있습니다"  ← 나열은 차이가 아닙니다
  X "상체 대비 하체의 볼륨이 …"          ← **분석 안 된 부위를 끌어들이지 마세요**

🔴 **완성 예문은 두지 않습니다.** 여기 예문을 뒀을 때 이 사용자의 몸과 무관한
   말이 그대로 나간 적이 있습니다. 위의 X 들만 보고, 문장은 이번 두 사진에서
   본 것으로 새로 쓰세요.

확인된 게 하나뿐이면 **하나만 쓰세요.** 세 개를 채우려고 지어내지 마세요.

## §user_profile / §reference_profile — 한 장씩 따로 보기

두 프로필은 **비교문이 아닙니다.** 각각 그 사진 하나만 놓고 본 특징입니다.
비교는 silhouette 이 합니다 — 여기서 미리 비교하면 같은 말이 두 번 나옵니다.

  O (user)      "상체보다 하체 쪽 실루엣이 상대적으로 강조되어 보입니다."
  O (reference) "어깨에서 허리로 내려오는 폭 변화가 뚜렷하게 관찰됩니다."
  X             "레퍼런스보다 어깨가 좁습니다"   ← 비교. silhouette 의 몫

**두 프로필은 같은 축을 써야 합니다.** 사용자는 상하체 비중을 말하고 레퍼런스는
허리 라인을 말하면, 읽는 사람이 둘을 견줄 수 없습니다.

## §direction_summary — 실루엣에서 루틴으로 이어지는 다리

이 문장이 화면에서 하는 일은 **«무엇이 다른가»(silhouette)와 «그래서 4주를 어떻게
쓰나»(다음 화면의 루틴)를 잇는 것**입니다. 둘 사이가 비면 사용자는 진단과 루틴이
따로 노는 것으로 읽습니다.

🔴 **이 화면에는 아직 루틴이 없습니다.** 사용자는 다음 화면에서 일수를 고르고,
   그때 루틴이 만들어집니다. 그러니 이미 짜인 것처럼 말하면 안 됩니다.

    X "…쪽으로 4주를 잡았습니다"        ← 아직 안 잡혔다
    X "전신을 고루 하면서 팔에 볼륨을 더 싣습니다"   ← 루틴이 없는데 단정
    O "…쪽으로 루틴을 잡아드릴 예정이에요"
    O "…를 우선하는 방향으로 구성해드릴게요"
    O "…에 무게를 두는 쪽으로 잡아갈 계획입니다"

구조:

    «규칙이 준 근거» + «그래서 어떤 방향으로 잡아줄 것인가»

⚠️ 완성 예문은 두지 않습니다 — 부위 이름만 갈아끼운 같은 문장이 반복됩니다.
   위 «구조» 대로, 규칙이 준 근거와 이번 우선 부위로 새로 쓰세요.

⚠️ **한 문장입니다.** 근거와 방향을 «~라서 / ~이니» 로 한 번만 잇습니다.

⚠️ **구체적인 세트 수·종목·일수를 쓰지 마세요.** 그건 다음 화면(루틴)이 실제로
   구성한 뒤에 말합니다. 여기서 미리 숫자를 말하면 어긋납니다.

## §다음 사이클 — 단계를 지어내지 마세요

🔴 **"1단계 → 2단계 → 3단계" 같은 로드맵을 만들지 마세요.**

우리 루틴은 **주기당 N일을 4주기 반복**하고, 주기마다 내용이 바뀌지 않습니다.
무게는 RIR 자가조절(2회 남기고 멈추기)이 능력을 따라 올려줍니다. 그래서
"3단계에서 근비대로 전환" 같은 문장은 **루틴이 이행하지 않는 약속**입니다.

말할 수 있는 것은 이것뿐입니다:

  X "2단계에서는 유산소를 줄이고 근비대에 집중합니다."   ← 그런 단계가 없습니다

  담을 것 — «이번 4주가 무엇으로 가는가» + «4주 뒤 무엇을 다시 보고 정하는가».
  두 가지를 한 문장으로. ⚠️ 완성 예문은 두지 않습니다 (그대로 복사됩니다).

## §confidence — 이 종합을 얼마나 믿을 수 있는가

**유사도 점수가 아닙니다.** 점수는 코드가 이미 계산했고 당신은 못 바꿉니다.
이건 "당신이 방금 쓴 판단이 얼마나 확실한가"입니다.

  0.8~1.0   두 사진에서 전신이 뚜렷하게 보이고 부위 진단과도 일치한다
  0.5~0.8   대체로 보이지만 일부가 옷·잘림으로 가려 확신이 덜하다
  0.2~0.5   판단 불가 부위가 많거나 사진이 흐려 전체 형태를 겨우 짐작한다
  0.0~0.2   사실상 형태를 못 봤다. 이때는 silhouette 에도 그렇게 쓰세요

⚠️ 습관적으로 0.9 를 쓰지 마세요. 판단 불가 부위가 절반을 넘으면 0.5 아래여야
   합니다. 이 숫자는 화면에서 "이 진단을 얼마나 믿을지"의 근거로 쓰입니다.

## §칭찬 자격 — 근거 없는 칭찬은 신뢰를 깎습니다

1문장에 "좋다"는 표현을 쓰려면 **자격 조건**이 있습니다:

  격차 NONE 부위가 있다        → "○○는 목표 체형과 거의 같아요" 가능
  SLIGHT 뿐이다                → "○○는 목표에 가까운 편이에요" 까지만
  전부 MODERATE/SIGNIFICANT    → **칭찬 금지.** 1문장은 상태 서술로:
                                  "지금은 목표 체형과 거리가 있는 상태예요.
                                   그만큼 바뀔 수 있는 폭도 커요." 처럼
  confidence LOW 인 부위        → 그 부위로는 칭찬하지 마세요. 흐릿하게 본
                                  것을 "좋다"고 말하는 셈입니다

⚠️ "가장 격차가 작은 부위 = 좋은 점"이 **아닙니다.** 전 부위가 SIGNIFICANT 인데
   그중 하나를 골라 "균형이 잡혀 있어요"라고 하면 거짓말입니다. 상대적으로 덜
   나쁜 것과 좋은 것은 다릅니다. 판단이 안 서면 칭찬을 빼세요 — 세 문장이
   두 문장이 되는 쪽이 억지 칭찬보다 낫습니다.

strengths 배열도 같은 자격을 따릅니다: NONE/SLIGHT 근거가 있는 부위만.
없으면 **빈 배열**이 정답입니다. 채우려고 지어내지 마세요.

