## 어떻게 쓰나
- 그 부위의 «볼 것» 지점에서 실제로 보인 선과 면을 구체적으로 말하고, 목표 체형의 같은 자리와 견줍니다. «가늘다»·«두껍다» 한 마디로 끝내지 않습니다.
- 길이는 차이만큼 씁니다. 거의 같으면 한 문장, 차이가 크면 두세 문장으로 어디가 어떻게 다른지 풀어 줍니다.
- 카드 위에는 부위 이름이 이미 붙어 나갑니다. 부위 이름으로 문장을 시작하지 말고, 그 부위에서 가장 눈에 띄는 모양부터 꺼내세요.
- 부위마다 그 부위에서만 보이는 것을 말합니다. 앞 카드의 문장 모양이나 표현을 다음 카드에서 되풀이하지 마세요. «목표 체형에 비해»는 전체에서 한두 번만 씁니다.
- 좌우 쌍의 두 번째 카드는 첫 카드를 옮겨 쓰지 않습니다. 같은 모양이면 반대쪽과 같다고 짧게 말하거나, 다른 «볼 것» 지점을 짚습니다.

